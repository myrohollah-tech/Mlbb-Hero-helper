fun MlbbRole.localizedName(strings: AppStrings): String = when (this) {
    MlbbRole.TANK -> strings.roleTank
    MlbbRole.FIGHTER -> strings.roleFighter
    MlbbRole.ASSASSIN -> strings.roleAssassin
    MlbbRole.MAGE -> strings.roleMage
    MlbbRole.MARKSMAN -> strings.roleMarksman
    MlbbRole.SUPPORT -> strings.roleSupport
}

fun MlbbLane.localizedName(strings: AppStrings): String = when (this) {
    MlbbLane.EXP -> strings.laneExp
    MlbbLane.GOLD -> strings.laneGold
    MlbbLane.MID -> strings.laneMid
    MlbbLane.JUNGLE -> strings.laneJungle
    MlbbLane.ROAM -> strings.laneRoam
}

